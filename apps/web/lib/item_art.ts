import type { EquipmentSlot, ItemKind } from "@darkforest/protocol";
import { itemArtPathsFor as sharedItemArtPathsFor } from "@/browser/item_art.js";

export type ItemArtCategory = "weapon" | "equipment" | "footwear" | "supply";
export type ItemArtAccent = "cyan" | "amber" | "moss";

export interface ItemArtEntry {
  kind: ItemKind;
  name: string;
  englishName: string;
  category: ItemArtCategory;
  slot: EquipmentSlot | "weapon" | "inventory" | "insight";
  slotLabel: string;
  fieldIcon: string;
  cardArt: string;
  outlineIcon: string | null;
  silhouette: string;
  summary: string;
  accent: ItemArtAccent;
}

function sharedArt(kind: ItemKind) {
  const art = sharedItemArtPathsFor(kind);
  if (art === null) throw new Error(`Missing shared item art paths: ${kind}`);
  return art;
}

