export function itemArtFor(kind: ItemKind): ItemArtEntry {
  const entry = ITEM_ART_CATALOG.find((candidate) => candidate.kind === kind);
  if (entry === undefined) throw new Error(`Missing item art entry: ${kind}`);
  return entry;
}
